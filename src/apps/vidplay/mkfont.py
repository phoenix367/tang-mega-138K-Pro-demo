#!/usr/bin/env python3
"""mkfont.py -- the OSD font of vidplay: DejaVu Sans rendered into an anti-aliased
8-bit alpha table for printable ASCII (osd_font.h).  DejaVu's licence (Bitstream
Vera) allows derived bitmaps.  Needs Pillow; the generated header is kept in the
repo, so building vidplay does not.

    mkfont.py [TTF] [PIXELS] > osd_font.h
"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
px = int(sys.argv[2]) if len(sys.argv) > 2 else 20
font = ImageFont.truetype(ttf, px)
asc, desc = font.getmetrics()
h = asc + desc
glyphs, data = [], []
for c in range(32, 127):
    ch = chr(c)
    adv = max(1, int(round(font.getlength(ch))))
    im = Image.new('L', (adv + 2, h), 0)
    ImageDraw.Draw(im).text((0, 0), ch, font=font, fill=255)
    w = adv + 2
    while w > 1 and not any(im.getpixel((w - 1, y)) for y in range(h)):
        w -= 1                                  # trim the empty right edge
    glyphs.append((len(data), w, adv))
    data += [im.getpixel((x, y)) for y in range(h) for x in range(w)]
out = ['/* osd_font.h -- generated by mkfont.py from %s at %d px: do not edit */' % (ttf.split('/')[-1], px),
       '#define OSD_FONT_H %d' % h, '#define OSD_FONT_FIRST 32', '#define OSD_FONT_LAST 126',
       'static const struct { unsigned short off; unsigned char w, adv; } osd_glyph[] = {']
out += ['    { %d, %d, %d },' % g for g in glyphs]
out += ['};', 'static const unsigned char osd_font_alpha[] = {']
for i in range(0, len(data), 24):
    out.append('    ' + ','.join(str(v) for v in data[i:i + 24]) + ',')
out.append('};')
print('\n'.join(out))
